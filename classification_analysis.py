from sklearn.linear_model import SGDClassifier
import numpy as np
from sklearn.datasets import make_blobs
import matplotlib.pyplot as plt

x,y = make_blobs(n_samples = 90, centers = 2, random_state = 0, cluster_std = 0.5)
classifier = SGDClassifier(loss = 'hinge', alpha = 0.001, max_iter = 350)
classifier.fit(x,y)
xx = np.linspace(-1,5,10)
yy = np.linspace(-1,5,10)
x1,x2 = np.meshgrid(xx,yy)
z = np.empty(x1.shape)
for (i,j), val in np.ndenumerate(x1):
  X1 = val
  X2 = x2[i,j]
  p = classifier.decision_function([[X1,X2]])
  z[i,j] = p[0]
levels = [-1.0, 0.0, 1.0]
linestyles = ['dashed', 'solid', 'dashed']
colors = 'k'
plt.contour(x1,x2,z, levels, colors = colors, linestyles = linestyles)
plt.scatter(x[:,0], x[:,1], c = y, cmap = plt.cm.Paired, edgecolors = 'black', s = 20)
plt.axis('tight')
plt.show()

